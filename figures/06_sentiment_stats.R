# 06 — Thesis Figure 6: classifier performance of the hybrid sentiment score
# under the three train-test approaches, for the China and US test data.
#
# Panel A repeats the Figure 6 statistics (three-class F1 by class, three-class
# accuracy). Panel B adds the statistics quoted in the Figure 7-8 text
# (accuracy on positive/negative documents only, one-vs-rest AUC by class).
#
# Input:  honors-thesis-original-data/sentiments/0X_metrics.csv
# Output: figures/output/06_sentiment_stats.tex  (booktabs table, \input-able)
#         figures/output/06_sentiment_stats_preview.pdf (standalone compile, for checking)

source(if (file.exists("figures/setup.R")) "figures/setup.R" else "setup.R")

metrics <- bind_rows(lapply(names(APPROACHES), function(a) {
  read_csv(out_path(paste0(a, "_metrics.csv")), show_col_types = FALSE,
           col_types = cols(approach = col_character()))
}))

get_metric <- function(a, ctry, m, cls) {
  v <- metrics$value[metrics$approach == a & metrics$country == ctry &
                       metrics$metric == m & metrics$class == cls]
  stopifnot(length(v) == 1)
  v
}
n_eval <- function(a, ctry) sum(metrics$value[metrics$approach == a & metrics$country == ctry &
                                                 metrics$metric == "n_eval_3class"])
n_binary <- function(a, ctry) sum(metrics$value[metrics$approach == a & metrics$country == ctry &
                                                   grepl("^binary_cm_", metrics$metric)])
f2 <- function(x) sprintf("%.2f", x)
pct <- function(x) sprintf("%.1f", 100 * x)

row_line <- function(cells) paste0(paste(cells, collapse = " & "), " \\\\")

panel_a <- sapply(names(APPROACHES), function(a) {
  cells <- unlist(lapply(c("China", "US"), function(ctry) {
    c(f2(get_metric(a, ctry, "f1_3class", "N")), f2(get_metric(a, ctry, "f1_3class", "O")),
      f2(get_metric(a, ctry, "f1_3class", "P")), pct(get_metric(a, ctry, "accuracy_3class", "all")),
      n_eval(a, ctry))
  }))
  row_line(c(APPROACH_SHORT[[a]], cells))
})

panel_b <- sapply(names(APPROACHES), function(a) {
  cells <- unlist(lapply(c("China", "US"), function(ctry) {
    c(f2(get_metric(a, ctry, "auc", "N")), f2(get_metric(a, ctry, "auc", "O")),
      f2(get_metric(a, ctry, "auc", "P")), pct(get_metric(a, ctry, "accuracy_binary", "P/N only")),
      n_binary(a, ctry))
  }))
  row_line(c(APPROACH_SHORT[[a]], cells))
})

tex <- c(
  "% Generated by figures/06_sentiment_stats.R -- do not edit by hand.",
  "% Requires \\usepackage{booktabs} and \\usepackage{threeparttable}.",
  "\\begin{table}[htbp]",
  "\\centering",
  "\\begin{threeparttable}",
  "\\caption{Performance of the hybrid sentiment classifier under three train-test approaches}",
  "\\label{tab:sentiment-stats}",
  "\\small",
  "\\begin{tabular}{l rrrrr @{\\hspace{1.5em}} rrrrr}",
  "\\toprule",
  " & \\multicolumn{5}{c}{China test data} & \\multicolumn{5}{c}{US test data} \\\\",
  "\\cmidrule(lr){2-6} \\cmidrule(lr){7-11}",
  "\\multicolumn{11}{l}{\\textit{A. Three classes}} \\\\[2pt]",
  " & \\multicolumn{3}{c}{F1} & Acc. & & \\multicolumn{3}{c}{F1} & Acc. & \\\\",
  "\\cmidrule(lr){2-4} \\cmidrule(lr){7-9}",
  " & Neg. & Amb. & Pos. & (\\%) & $n$ & Neg. & Amb. & Pos. & (\\%) & $n$ \\\\",
  "\\midrule",
  panel_a,
  "\\midrule",
  "\\multicolumn{11}{l}{\\textit{B. One-vs-rest AUC and positive/negative accuracy}} \\\\[2pt]",
  " & \\multicolumn{3}{c}{AUC} & Acc. & & \\multicolumn{3}{c}{AUC} & Acc. & \\\\",
  "\\cmidrule(lr){2-4} \\cmidrule(lr){7-9}",
  " & Neg. & Amb. & Pos. & (\\%) & $n$ & Neg. & Amb. & Pos. & (\\%) & $n$ \\\\",
  "\\midrule",
  panel_b,
  "\\bottomrule",
  "\\end{tabular}",
  "\\begin{tablenotes}[flushleft]",
  "\\footnotesize",
  "\\item \\textit{Notes:} The hybrid score averages the SVM label, the random forest label and the standardized Bing Liu lexicon score.",
  "Approach 1 trains on positive and negative documents only; approach 2 adds a sample of 75 ambiguous documents;",
  "approach 3 trains separate positive-vs-not and negative-vs-not models and combines them.",
  "Panel A: the continuous hybrid score is cut into three classes at quantiles matching the share of each hand-coded class in the evaluation set;",
  "for approach 1, which has no ambiguous documents in its test split, held-out ambiguous documents are added to the evaluation set.",
  "Panel B: AUC treats each class in turn as the outcome and the hybrid score as the predictor, with the direction of the score chosen for each class (the pROC default);",
  "accuracy classifies hand-coded positive and negative documents by the sign of the hybrid score.",
  "$n$ is the number of evaluation documents.",
  "\\end{tablenotes}",
  "\\end{threeparttable}",
  "\\end{table}"
)
writeLines(tex, fig_path("06_sentiment_stats.tex"))

# Standalone preview, compiled in a temp dir so LaTeX auxiliary files stay out of the repo.
preview_dir <- tempfile("tex_preview_")
dir.create(preview_dir)
writeLines(c("\\documentclass[11pt]{article}",
             "\\usepackage[margin=1in]{geometry}",
             "\\usepackage{booktabs,threeparttable}",
             "\\pagestyle{empty}",
             "\\begin{document}",
             sprintf("\\input{%s}", normalizePath(fig_path("06_sentiment_stats.tex"))),
             "\\end{document}"),
           file.path(preview_dir, "preview.tex"))
status <- system2("pdflatex", c("-interaction=nonstopmode", "-halt-on-error",
                                paste0("-output-directory=", shQuote(preview_dir)),
                                shQuote(file.path(preview_dir, "preview.tex"))),
                  stdout = FALSE, stderr = FALSE)
if (status == 0) {
  file.copy(file.path(preview_dir, "preview.pdf"), fig_path("06_sentiment_stats_preview.pdf"), overwrite = TRUE)
} else {
  warning("pdflatex failed; see ", file.path(preview_dir, "preview.log"))
}
cat(tex[grepl("^Approach", tex)], sep = "\n")
cat("Done: 06_sentiment_stats\n")
